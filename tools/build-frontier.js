/*
 * Precomputes the expected annual loss of every control portfolio
 * (2^12 = 4,096 combinations) at best-estimate inputs, using common random
 * numbers so portfolios are compared on identical simulated incidents.
 *
 *   node tools/build-frontier.js        → writes Js/frontier.js
 *
 * Re-run whenever Js/data.js changes; the page checks the data hash and
 * recomputes in the browser if the table is stale.
 */
const fs = require('fs'), path = require('path');
const D = require('../Js/data.js'), E = require('../Js/engine.js');
const n = 1 << D.CONTROLS.length, runs = D.MODEL.frontierRuns;
const t0 = Date.now(), ale = [];
for (let from = 0; from < n; from += 256) {
  const part = E.frontierRange(D, from, Math.min(n, from + 256), runs);
  for (const v of part) ale.push(Math.round(v));
  process.stdout.write('\r' + ale.length + '/' + n);
}
const out = '/* generated by tools/build-frontier.js — do not edit */\n' +
  '(function (root) {\n  var T = ' + JSON.stringify({ hash: E.dataHash(D), runs: runs, controls: D.CONTROLS.map(c => c.id), ale: ale }) + ';\n' +
  '  if (typeof module !== "undefined" && module.exports) module.exports = T; else root.BSFrontier = T;\n' +
  '})(typeof self !== "undefined" ? self : this);\n';
fs.writeFileSync(path.join(__dirname, '..', 'Js', 'frontier.js'), out);
const idx = E.portfolioIndex(D, Float64Array.from(ale));
const show = m => E.idsOf(D, m).join(', ') + '  cost $' + idx.cost[m] + '  ALE $' + Math.round(idx.ale[m]) + '  TCoR $' + Math.round(idx.tcor[m]);
console.log('\n' + ((Date.now() - t0) / 1000).toFixed(1) + 's, ' + (out.length / 1024).toFixed(0) + ' KB');
console.log('optimum      :', show(idx.optimum));
console.log('optimum ≤$120K:', show(idx.optimumBudget));
console.log('pareto points:', idx.pareto.length);
